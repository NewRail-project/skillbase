const DICTIONARY = {
  [MODES.EDUCATION]: {},
  [MODES.WORKFORCE]: {}
};
for (const [key, edu, work] of ENTRIES) {
  DICTIONARY[MODES.EDUCATION][key] = edu;
  DICTIONARY[MODES.WORKFORCE][key] = work;
}

function fill(text, params) {
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in params ? String(params[name]) : m));
}

/**
 * Строка по ключу для текущего (или явно заданного) режима.
 * @param {string} key
 * @param {Object|string} [paramsOrMode] подстановки {name} либо режим
 * @param {string} [overrideMode]
 */
export function t(key, paramsOrMode, overrideMode) {
  let params = null;
  let mode = overrideMode;
  if (typeof paramsOrMode === "string") mode = paramsOrMode;
  else if (paramsOrMode) params = paramsOrMode;
  mode = mode || getMode();
  const dict = DICTIONARY[mode] || DICTIONARY[MODES.EDUCATION];
  const text = dict[key] ?? DICTIONARY[MODES.EDUCATION][key] ?? key;
  return fill(text, params);
}

/** Функция для h(): живой текст/атрибут, обновляется при смене режима. */
export function lt(key, params) {
  return () => t(key, params);
}

/** Подпись роли. Сама роль в профиле не меняется — меняется только слово на экране. */
export function roleLabel(role, { lower = false } = {}) {
  const base = role === "teacher" ? "teacher" : role === "admin" ? "admin" : "student";
  return t(`role.${base}${lower ? "Lc" : ""}`);
}

/** Все ключи словаря (для тестов). */
export function dictionaryKeys(mode) {
  return Object.keys(DICTIONARY[mode] || {});
}

export { DICTIONARY };
